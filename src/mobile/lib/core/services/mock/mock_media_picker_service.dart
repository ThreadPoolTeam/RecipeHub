import 'dart:typed_data';

import '../../models/session_models.dart';
import '../interfaces/i_media_picker_service.dart';

/// Trả ảnh PNG 1×1 hợp lệ (hoặc ảnh "quá cỡ" để test giới hạn 5MB).
class MockMediaPickerService implements IMediaPickerService {
  MockMediaPickerService({this.returnOversized = false, this.cancel = false});

  bool returnOversized;
  bool cancel;

  static final Uint8List _png1x1 = Uint8List.fromList(const [
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
    0x89, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0xF8, 0xCF, 0xC0, 0xF0,
    0x1F, 0x00, 0x05, 0x00, 0x01, 0xFF, 0x89, 0x99, 0x3D, 0x1D, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45,
    0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
  ]);

  @override
  Future<PickedMedia?> pickImage({required bool fromCamera}) async {
    if (cancel) return null;
    if (returnOversized) {
      return PickedMedia(
        bytes: Uint8List(6 * 1024 * 1024),
        fileName: 'oversized_capture.jpg',
        mimeType: 'image/jpeg',
      );
    }
    return PickedMedia(
      bytes: _png1x1,
      fileName: fromCamera ? 'counter_capture.png' : 'gallery_pick.png',
      mimeType: 'image/png',
    );
  }
}
