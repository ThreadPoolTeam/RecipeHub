-- 4. Trigger Functions
-- 4.1 Cardinality check trigger (deferred constraint trigger across transaction)
CREATE OR REPLACE FUNCTION recipe_db.trg_check_pdf_document_cardinality()
RETURNS trigger AS $$
DECLARE
    v_doc_id bigint;
    v_scope text;
    v_count integer;
    v_expected_sum integer;
    v_actual_sum integer;
    v_min_order integer;
    v_max_order integer;
BEGIN
    IF TG_TABLE_NAME = 'pdf_document' THEN
        v_doc_id := NEW.id;
        v_scope := NEW.export_scope;
    ELSE
        v_doc_id := COALESCE(NEW.document_id, OLD.document_id);
        SELECT export_scope INTO v_scope FROM recipe_db.pdf_document WHERE id = v_doc_id;
    END IF;

    -- Only check if document exists (not in case document is being deleted)
    IF v_scope IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT COUNT(*), COALESCE(MIN(sort_order), 0), COALESCE(MAX(sort_order), 0), COALESCE(SUM(sort_order), 0)
    INTO v_count, v_min_order, v_max_order, v_actual_sum
    FROM recipe_db.pdf_document_item
    WHERE document_id = v_doc_id;

    IF v_scope = 'single' AND v_count <> 1 THEN
        RAISE EXCEPTION 'Single recipe PDF document % must have exactly 1 item, but has %', v_doc_id, v_count;
    END IF;

    IF v_scope = 'collection' AND v_count < 2 THEN
        RAISE EXCEPTION 'Collection recipe PDF document % must have at least 2 items, but has %', v_doc_id, v_count;
    END IF;

    -- Check continuous sort_order 1..N
    v_expected_sum := (v_count * (v_count + 1)) / 2;
    IF v_min_order <> 1 OR v_max_order <> v_count OR v_actual_sum <> v_expected_sum THEN
        RAISE EXCEPTION 'PDF document % items must have continuous sort_order from 1 to %, actual min: %, max: %',
            v_doc_id, v_count, v_min_order, v_max_order;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- 4.2 Immutability trigger for pdf_document:
-- If state was 'ready', only audit_published_at and audit_recorded_at can be updated. Deletes blocked.
CREATE OR REPLACE FUNCTION recipe_db.trg_enforce_pdf_document_immutability()
RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.state = 'ready' THEN
            RAISE EXCEPTION 'Cannot delete ready PDF document %; ready documents are immutable.', OLD.id;
        END IF;
        RETURN OLD;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.state = 'ready' THEN
            -- Allow only audit_published_at and audit_recorded_at modifications
            IF NEW.id <> OLD.id OR
               NEW.public_id <> OLD.public_id OR
               NEW.title <> OLD.title OR
               NEW.document_type <> OLD.document_type OR
               NEW.export_scope <> OLD.export_scope OR
               NEW.state <> OLD.state OR
               NEW.template_code <> OLD.template_code OR
               NEW.template_version <> OLD.template_version OR
               NEW.presentation_snapshot::text <> OLD.presentation_snapshot::text OR
               NEW.snapshot_sha256 <> OLD.snapshot_sha256 OR
               NEW.created_by_user_ref <> OLD.created_by_user_ref OR
               NEW.created_at <> OLD.created_at OR
               NEW.completed_at IS DISTINCT FROM OLD.completed_at OR
               NEW.lease_token IS DISTINCT FROM OLD.lease_token OR
               NEW.lease_expires_at IS DISTINCT FROM OLD.lease_expires_at OR
               NEW.storage_provider <> OLD.storage_provider OR
               NEW.storage_public_id <> OLD.storage_public_id OR
               NEW.storage_asset_id IS DISTINCT FROM OLD.storage_asset_id OR
               NEW.storage_version IS DISTINCT FROM OLD.storage_version OR
               NEW.storage_resource_type <> OLD.storage_resource_type OR
               NEW.storage_delivery_type <> OLD.storage_delivery_type OR
               NEW.file_name <> OLD.file_name OR
               NEW.byte_size IS DISTINCT FROM OLD.byte_size OR
               NEW.file_sha256 IS DISTINCT FROM OLD.file_sha256 OR
               NEW.error_code IS DISTINCT FROM OLD.error_code OR
               NEW.storage_cleanup_required <> OLD.storage_cleanup_required OR
               NEW.audit_event_id <> OLD.audit_event_id THEN
                RAISE EXCEPTION 'Ready PDF document % is immutable. Only audit timestamps may be updated.', OLD.id;
            END IF;
        END IF;
        RETURN NEW;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 4.3 Immutability trigger for pdf_document_item:
-- If parent is 'ready', cannot INSERT/UPDATE/DELETE items.
CREATE OR REPLACE FUNCTION recipe_db.trg_enforce_pdf_document_item_immutability()
RETURNS trigger AS $$
DECLARE
    v_doc_id bigint;
    v_state text;
BEGIN
    v_doc_id := COALESCE(NEW.document_id, OLD.document_id);
    SELECT state INTO v_state FROM recipe_db.pdf_document WHERE id = v_doc_id FOR SHARE;

    IF v_state = 'ready' THEN
        RAISE EXCEPTION 'Cannot modify or delete items of ready PDF document %; document is immutable.', v_doc_id;
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

